std::shared_ptr<Media::PixelMap> CreateTestPixelMap(int32_t width, int32_t height)
{
    if (width <= 0 || height <= 0) {
        return nullptr;
    }
    const int32_t bytesPerPixel = RGBA_BYTES_PER_PIXEL;
    const size_t dataSize = static_cast<size_t>(width) * height * bytesPerPixel;
    auto data = std::make_unique<uint8_t[]>(dataSize);

    // Mixed pattern: left half = color gradient, right half = B/W checkerboard
    // gradientHalfW is 0 only for width <= 1, where the gradient branch below is unreachable
    const int32_t gradientHalfW = width / CHECKERBOARD_PARITY;
    const int32_t checkerSize = CHECKERBOARD_CELL_SIZE;
    for (int32_t y = 0; y < height; y++) {
        for (int32_t x = 0; x < width; x++) {
            const size_t idx = (static_cast<size_t>(y) * width + x) * bytesPerPixel;
            if (x < gradientHalfW) {
                data[idx] = static_cast<uint8_t>(RGBA_CHANNEL_MAX * y / std::max(height, 1));
                data[idx + RGBA_GREEN_CHANNEL] = static_cast<uint8_t>(RGBA_CHANNEL_MAX * x / gradientHalfW);
                data[idx + RGBA_BLUE_CHANNEL] =
                    static_cast<uint8_t>(RGBA_CHANNEL_MAX - RGBA_CHANNEL_MAX * y / std::max(height, 1));
            } else {
                const int32_t bx = (x - gradientHalfW) / checkerSize;
                const int32_t by = y / checkerSize;
                const uint8_t v = ((bx + by) % CHECKERBOARD_PARITY == 0) ? RGBA_CHANNEL_MAX : 0;
                data[idx] = v;
                data[idx + RGBA_GREEN_CHANNEL] = v;
                data[idx + RGBA_BLUE_CHANNEL] = v;
            }
            data[idx + RGBA_ALPHA_CHANNEL] = RGBA_CHANNEL_MAX;
        }
    }

    Media::InitializationOptions opts;
    opts.size.width = width;
    opts.size.height = height;
    opts.pixelFormat = Media::PixelFormat::RGBA_8888;
    opts.alphaType = OHOS::Media::AlphaType::IMAGE_ALPHA_TYPE_OPAQUE;
    opts.editable = true;

    auto pixelmap = Media::PixelMap::Create(
        reinterpret_cast<const uint32_t*>(data.get()), dataSize, opts);
    if (pixelmap == nullptr) {
        std::cout << "CreateTestPixelMap: PixelMap::Create failed" << std::endl;
        return nullptr;
    }
    return pixelmap;
}

