constexpr int32_t STICKER_ALPHA_CHANNEL = 3;
constexpr int32_t STICKER_CELL_SIZE = 64;  // checkerboard cell size in px
constexpr int32_t STICKER_CHECKER_PARITY = 2;
constexpr uint8_t STICKER_COLOR_MAX = 255;
